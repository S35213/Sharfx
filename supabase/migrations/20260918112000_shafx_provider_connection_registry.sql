create or replace function public.create_shafx_provider_secret(p_secret text, p_name text, p_description text default null)
returns uuid language plpgsql security definer set search_path = public, vault as $$
declare v_id uuid;
begin
  if current_user not in ('service_role','supabase_admin','postgres') then raise exception 'provider secret storage is service-only'; end if;
  if coalesce(length(trim(p_secret)),0) < 16 then raise exception 'provider secret is too short'; end if;
  select vault.create_secret(p_secret, p_name, p_description) into v_id;
  return v_id;
end;
$$;

create or replace function public.read_shafx_provider_secret(p_secret_id uuid)
returns text language plpgsql security definer set search_path = public, vault as $$
declare v_secret text;
begin
  if current_user not in ('service_role','supabase_admin','postgres') then raise exception 'provider secret reads are service-only'; end if;
  select decrypted_secret into v_secret from vault.decrypted_secrets where id = p_secret_id;
  if v_secret is null then raise exception 'provider secret not found'; end if;
  return v_secret;
end;
$$;

create or replace function public.delete_shafx_provider_secret(p_secret_id uuid)
returns boolean language plpgsql security definer set search_path = public, vault as $$
begin
  if current_user not in ('service_role','supabase_admin','postgres') then raise exception 'provider secret deletion is service-only'; end if;
  delete from vault.secrets where id = p_secret_id;
  return found;
end;
$$;

