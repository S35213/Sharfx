-- Durable multi-provider connection/account registry and server-only provider secret references.

create table if not exists public.shafx_provider_connections (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider_id text not null,
  label text not null default '',
  environment text not null default 'mixed' check (environment in ('demo','live','mixed')),
  state text not null default 'disconnected' check (state in ('connected','expired','disconnected','error')),
  auth_method text not null default 'oauth2' check (auth_method in ('oauth2','api_key','pat','custom')),
  credential_ref uuid,
  provider_subject text,
  expires_at timestamptz,
  last_seen_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists shafx_provider_connections_user_idx on public.shafx_provider_connections (user_id, created_at desc);
create index if not exists shafx_provider_connections_provider_idx on public.shafx_provider_connections (provider_id, state);

create table if not exists public.shafx_provider_accounts (
  id uuid primary key default gen_random_uuid(),
  connection_id uuid not null references public.shafx_provider_connections(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  provider_id text not null,
  provider_account_id text not null,
  label text,
  environment text not null check (environment in ('demo','live')),
  currency text,
  balance numeric,
  equity numeric,
  used_margin numeric,
  free_margin numeric,
  floating_pl numeric,
  active boolean not null default true,
  last_synced_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, provider_id, provider_account_id, environment)
);

create index if not exists shafx_provider_accounts_connection_idx on public.shafx_provider_accounts (connection_id, active);
create index if not exists shafx_provider_accounts_user_idx on public.shafx_provider_accounts (user_id, provider_id, environment);

create table if not exists public.shafx_provider_order_intents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  connection_id uuid not null references public.shafx_provider_connections(id) on delete restrict,
  account_id uuid not null references public.shafx_provider_accounts(id) on delete restrict,
  client_order_id text not null,
  provider_order_id text,
  state text not null default 'unknown' check (state in ('accepted','rejected','unknown','reconciled','cancelled')),
  request jsonb not null default '{}'::jsonb,
  result jsonb,
  error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (connection_id, client_order_id)
);

create index if not exists shafx_provider_order_intents_account_idx on public.shafx_provider_order_intents (account_id, created_at desc);
create index if not exists shafx_provider_order_intents_user_idx on public.shafx_provider_order_intents (user_id, created_at desc);

create table if not exists public.shafx_provider_audit_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  connection_id uuid references public.shafx_provider_connections(id) on delete set null,
  account_id uuid references public.shafx_provider_accounts(id) on delete set null,
  event_type text not null,
  severity text not null default 'info' check (severity in ('info','warning','error','critical')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists shafx_provider_audit_events_user_idx on public.shafx_provider_audit_events (user_id, created_at desc);
create index if not exists shafx_provider_audit_events_connection_idx on public.shafx_provider_audit_events (connection_id, created_at desc);

create or replace function public.set_shafx_provider_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

