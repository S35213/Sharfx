create or replace function public.claim_shafx_bot_run(p_worker text)
returns table (
  id uuid,
  user_id uuid,
  connection_id uuid,
  account_row_id uuid,
  symbol text,
  stake numeric,
  multiplier_mode text,
  multiplier numeric,
  plan text,
  unit_number integer,
  current_round integer,
  completed_rounds integer,
  status text,
  next_action_at timestamptz,
  cancel_requested boolean,
  total_profit numeric,
  total_loss numeric,
  net_profit numeric,
  locked_until timestamptz
)
language plpgsql security definer set search_path = public as $$
declare v_run public.shafx_bot_runs;
begin
  if current_user not in ('service_role','supabase_admin','postgres') then
    raise exception 'bot worker claim is service-only';
  end if;

  select * into v_run
  from public.shafx_bot_runs
  where status in ('queued','scanning','waiting','buying','open','closing','cancel_requested')
    and next_action_at <= now()
    and (locked_until is null or locked_until < now())
  order by next_action_at asc, created_at asc
  for update skip locked
  limit 1;

  if not found then return; end if;

  update public.shafx_bot_runs
     set locked_by = p_worker,
         locked_until = now() + interval '20 seconds',
         last_heartbeat_at = now(),
         status = case when status = 'queued' then 'scanning' else status end
   where public.shafx_bot_runs.id = v_run.id
   returning * into v_run;

  return query
  select v_run.id, v_run.user_id, v_run.connection_id, v_run.account_row_id, v_run.symbol,
         v_run.stake, v_run.multiplier_mode, v_run.multiplier, v_run.plan, v_run.unit_number,
         v_run.current_round, v_run.completed_rounds, v_run.status, v_run.next_action_at,
         v_run.cancel_requested, v_run.total_profit, v_run.total_loss, v_run.net_profit, v_run.locked_until;
end;
$$;

revoke execute on function public.set_shafx_bot_updated_at() from public, anon, authenticated;
revoke execute on function public.claim_shafx_bot_run(text) from public, anon, authenticated;
grant execute on function public.set_shafx_bot_updated_at() to service_role;
grant execute on function public.claim_shafx_bot_run(text) to service_role;
